#!/usr/bin/env node
/* Assemble one file that loads a batch into the CRM: leads, their contact
   routes, and their unapproved drafts.

   Written as a file rather than executed directly because the anon key cannot
   write to sales_leads and there is no service key on this machine. It is
   idempotent — `on conflict do nothing` on the leads, and the contacts and
   drafts are keyed by company name so re-running adds nothing twice.

     node scripts/sourcing/build-load-sql.mjs
*/

import fs from 'node:fs'
import path from 'node:path'

const arg = (f, d) => { const i = process.argv.indexOf(f); return i > -1 && process.argv[i + 1] ? process.argv[i + 1] : d }
const OUT = arg('--out', '.sourcing/load-batch.sql')

const q = (v) => {
  if (v === null || v === undefined || v === '') return 'null'
  if (typeof v === 'number') return String(v)
  return `'${String(v).replace(/'/g, "''")}'`
}

const parts = []
for (const f of ['.sourcing/batchA.sql', '.sourcing/batchB.sql']) {
  if (!fs.existsSync(f)) { console.error(`missing ${f}`); process.exit(1) }
  parts.push(fs.readFileSync(f, 'utf8'))
}

const drafts = JSON.parse(fs.readFileSync('.sourcing/drafts.json', 'utf8')).drafts

/* Drafts are inserted unapproved: approved_at stays null, so the CRM's
   "Record and open in mail" button is locked until a human approves the exact
   text. Approval belongs to a body of text, not to a lead. */
const draftSql = drafts.length ? [
  '',
  '-- Drafts, unapproved. approved_at is null on purpose: the CRM locks the',
  '-- send button until a human approves the exact wording, and editing the',
  '-- text lapses the approval again.',
  'insert into public.sales_email_drafts (lead_id, subject, body)',
  drafts.map((d) =>
    `select id, ${q(d.subject)}, ${q(d.body)} from public.sales_leads where company = ${q(d.company)}`,
  ).join('\nunion all\n'),
  ';',
] .join('\n') : ''

const header = [
  '-- Generated by scripts/sourcing/build-load-sql.mjs.',
  '-- Leads, their published contact routes, and one unapproved draft each.',
  '-- Every lead lands on do_not_contact: loading is not approval, and the',
  '-- compliance gate is asked again at send time regardless.',
  '',
].join('\n')

fs.writeFileSync(OUT, header + parts.join('\n\n') + draftSql + '\n')
const size = fs.statSync(OUT).size
console.log(`
  ${drafts.length} drafts, plus the two lead batches
  -> ${path.resolve(OUT)}  (${Math.round(size / 1024)} KB)
`)
