#!/usr/bin/env node
/* Load business/knowledge/services into the database, as a migration.

   The lead-gen agents read what each service is from public.prospect_knowledge.
   The source of truth is the markdown in the repository, so that what a
   specialist believes can be argued with in a diff. This script is the only
   road between the two.

     node scripts/build-service-knowledge.mjs          write a migration + manifest
     node scripts/build-service-knowledge.mjs --check  fail if the folders have
                                                       changed since the last one

   Why a migration and not a runtime read of the files: the edge function is
   deployed without the repository, and a copy bundled into it would change
   only on a deploy. A row changes on the next tick after the migration runs.

   Which folders may exist is not decided here. The generated SQL refuses to
   load a service that is not an active `capability` term in
   public.outreach_vocabulary, so the set of services is the CRM's set, held in
   one place. */

import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DIR = join(ROOT, 'business', 'knowledge', 'services')
const MANIFEST = join(DIR, 'manifest.json')
const MIGRATIONS = join(ROOT, 'supabase', 'migrations')

export const REQUIRED = [
  'In one paragraph',
  'Signals that point here',
  'Signals that point somewhere else',
  'What we would build',
  'What kills it',
  'How this specialist scores',
  'The question that settles it',
]

/* Past this, a specialist's knowledge stops fitting comfortably beside the
   lead it is arguing about. A red build beats a prompt that is silently cut. */
const MAX_CHARS = 9000

const sha = (s) => createHash('sha256').update(s).digest('hex')

export function sections(md) {
  const out = {}
  let head = null
  for (const line of md.split('\n')) {
    const m = line.match(/^##\s+(.+?)\s*$/)
    if (m) { head = m[1]; out[head] = []; continue }
    if (head) out[head].push(line)
  }
  for (const k of Object.keys(out)) out[k] = out[k].join('\n').trim()
  return out
}

export function readKnowledge(dir = DIR) {
  const rows = []
  const problems = []

  const shared = join(dir, '_shared')
  for (const f of readdirSync(shared).filter((f) => f.endsWith('.md')).sort()) {
    const body = readFileSync(join(shared, f), 'utf8')
    rows.push({ key: f.replace(/\.md$/, ''), kind: 'shared', label: (body.match(/^#\s+(.+)$/m) || [])[1] || f,
      body, summary: null, signals: null, file: `_shared/${f}`, sha: sha(body) })
  }

  for (const d of readdirSync(dir).filter((d) => !d.startsWith('_') && statSync(join(dir, d)).isDirectory()).sort()) {
    const file = join(dir, d, 'service.md')
    if (!existsSync(file)) { problems.push(`${d}/ has no service.md`); continue }
    if (!/^[a-z][a-z0-9_]*$/.test(d)) { problems.push(`${d}/ is not a capability-shaped name`); continue }
    const body = readFileSync(file, 'utf8')
    const s = sections(body)
    for (const h of REQUIRED) if (!s[h]) problems.push(`${d}/service.md is missing "## ${h}"`)
    if (body.length > MAX_CHARS) problems.push(`${d}/service.md is ${body.length} characters; the ceiling is ${MAX_CHARS}`)
    rows.push({ key: d, kind: 'service', label: (body.match(/^#\s+(.+)$/m) || [])[1] || d,
      body, summary: s['In one paragraph'] ?? null, signals: s['Signals that point here'] ?? null,
      file: `${d}/service.md`, sha: sha(body) })
  }
  return { rows, problems }
}

/* Dollar quoting with a tag the text cannot contain, so no escaping rule has
   to be right for every character a person might type into a markdown file. */
function lit(s) {
  if (s == null) return 'null'
  let tag = 'k'
  while (String(s).includes(`$${tag}$`)) tag += 'k'
  return `$${tag}$${s}$${tag}$`
}

export function migrationSql(rows, stamp) {
  const services = rows.filter((r) => r.kind === 'service').map((r) => `'${r.key}'`).join(', ')
  const values = rows.map((r) =>
    `  (${lit(r.key)}, ${lit(r.kind)}, ${lit(r.label)}, ${lit(r.body)}, ${lit(r.summary)}, ${lit(r.signals)}, '${r.sha}')`)
  return `-- Generated by scripts/build-service-knowledge.mjs on ${stamp}. Do not edit:
-- change business/knowledge/services and run \`npm run knowledge:services\`.

do $$
declare missing text;
begin
  select string_agg(k, ', ') into missing
    from unnest(array[${services}]::text[]) k
   where not exists (select 1 from public.outreach_vocabulary v
                      where v.dimension = 'capability' and v.term = k and v.active);
  if missing is not null then
    raise exception 'business/knowledge/services has folders that are not active capability terms: %', missing;
  end if;
end $$;

insert into public.prospect_knowledge (key, kind, label, body, summary, signals, sha256)
values
${values.join(',\n')}
on conflict (key) do update
   set kind = excluded.kind, label = excluded.label, body = excluded.body,
       summary = excluded.summary, signals = excluded.signals,
       sha256 = excluded.sha256, active = true, updated_at = now();

-- A folder that was removed stops being a service the agents may argue for.
update public.prospect_knowledge
   set active = false, updated_at = now()
 where key not in (${rows.map((r) => `'${r.key}'`).join(', ')});
`
}

function main() {
  const check = process.argv.includes('--check')
  const { rows, problems } = readKnowledge()
  if (problems.length) {
    console.error(`\n  business/knowledge/services is not loadable:\n${problems.map((p) => `   - ${p}`).join('\n')}\n`)
    process.exit(1)
  }
  const files = Object.fromEntries(rows.map((r) => [r.file, r.sha]))

  if (check) {
    const m = existsSync(MANIFEST) ? JSON.parse(readFileSync(MANIFEST, 'utf8')) : null
    const drift = []
    if (!m) drift.push('no manifest.json — run npm run knowledge:services')
    else {
      for (const [f, h] of Object.entries(files)) if (m.files?.[f] !== h) drift.push(`${f} changed since ${m.migration}`)
      for (const f of Object.keys(m.files ?? {})) if (!(f in files)) drift.push(`${f} was removed since ${m.migration}`)
      if (!existsSync(join(MIGRATIONS, m.migration ?? ''))) drift.push(`${m.migration} is named in the manifest but does not exist`)
      else {
        const sql = readFileSync(join(MIGRATIONS, m.migration), 'utf8')
        for (const h of Object.values(files)) if (!sql.includes(h)) drift.push(`${m.migration} does not carry ${h.slice(0, 12)}`)
      }
    }
    if (drift.length) {
      console.error(`\n  The agents are not reading what the repository says:\n${drift.map((d) => `   - ${d}`).join('\n')}\n  Run: npm run knowledge:services, then apply the migration.\n`)
      process.exit(1)
    }
    console.log(`  service knowledge: ${rows.length} files, all loaded by ${m.migration}`)
    return
  }

  const now = new Date()
  const p = (n) => String(n).padStart(2, '0')
  const stamp = `${now.getUTCFullYear()}${p(now.getUTCMonth() + 1)}${p(now.getUTCDate())}${p(now.getUTCHours())}${p(now.getUTCMinutes())}`
  const name = `${stamp}_service_knowledge_${sha(Object.values(files).join('')).slice(0, 8)}.sql`
  writeFileSync(join(MIGRATIONS, name), migrationSql(rows, now.toISOString()))
  writeFileSync(MANIFEST, JSON.stringify({ migration: name, files }, null, 2) + '\n')
  console.log(`  wrote supabase/migrations/${name}\n  ${rows.length} files: ${rows.map((r) => r.key).join(', ')}\n  Apply it, and the next tick reads the new text.`)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main()
