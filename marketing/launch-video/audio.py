def build_music_file():
    """A generated track (musicgen.py) fitted to the cut. film.py names it,
    MUSIC_FILE in films/<id>/music, and MUSIC_AT, the downbeat in the file
    (seconds) that lands on the drop. The film's BPM is the track's, so every
    cut still falls on a beat. Before the drop its low end is held back and a
    filter opens, so it all lands on the drop; it goes muffled for each m_lpf cue and stops dead for the press
    (m_gap), running on underneath, so it comes back on the beat under the
    name. If the file runs out, it loops back whole bars (MUSIC_LOOP, 4)."""
    y, sr = sf.read(os.path.join(HERE, "films", FILM_ID, "music", F.MUSIC_FILE), dtype="float64", always_2d=True)
    y = np.repeat(y, 2, 1) if y.shape[1] == 1 else y[:, :2]
    g = np.gcd(SR, sr)
    y = signal.resample_poly(y, SR // g, sr // g, axis=0)
    drop, g0, g1, secB, secC, fills, lpfs = reel_markers()
    start = at(getattr(F, "MUSIC_AT", 0.0)) - at(drop)       # the file's sample under film time 0
    # the last whole bar before the take trails off
    live = np.flatnonzero(np.abs(y).max(1) > 10 ** (-40 / 20))
    bar = 4 * BEAT
    end = at(getattr(F, "MUSIC_AT", 0.0)) + at(bar * np.floor((live[-1] / SR - 0.3 - getattr(F, "MUSIC_AT", 0.0)) / bar))
    loop = at(getattr(F, "MUSIC_LOOP", 4) * bar)
    xf = at(0.03); fade_in = np.sqrt(np.linspace(0, 1, xf))[:, None]; fade_out = fade_in[::-1]
    src = y[:end]
    while start + N > len(src):                               # loop whole bars back, crossfaded just before the bar line
        seg = y[end - loop - xf:end]
        src = np.concatenate([src[:-xf], src[-xf:] * fade_out + seg[:xf] * fade_in, seg[xf:]])
    music = np.zeros((N, 2))
    lo, hi = max(0, -start), min(N, len(src) - start)
    music[lo:hi] = src[start + lo:start + hi]
    # before the drop: no low end (the kick and bass are held back) and a
    # filter opening, so everything lands at once on the drop
    i0 = at(drop); cut = 600 * (6000 / 600) ** (np.arange(i0) / max(i0, 1)) ** 2
    pre = sweep_lp(hp(music[:i0], 280, 4), cut) * np.linspace(1.0, 1.8, i0)[:, None]
    music[:i0] = pre * np.clip(np.arange(i0) / SR / 0.05, 0, 1)[:, None]
    rc = hp(noise(drop), 2000); rc = rc * np.linspace(0, 1, len(rc)) ** 3   # and a rush of air into it
    for c in lpfs:                                            # muffled while the objection glows
        a, z = c["t"], c["t"] + c["d"]
        w = np.clip(np.minimum((np.arange(N) / SR - a) / 0.08, (z - np.arange(N) / SR) / 0.12), 0, 1)
        music = music * (1 - w)[:, None] + lp(music, 520, 4) * w[:, None]
    gate = np.ones(N); gate[at(g0):at(g1)] = 0
    ramp = at(0.012); gate[at(g0):at(g0) + ramp] = np.linspace(1, 0, ramp); gate[at(g1) - ramp:at(g1)] = np.linspace(0, 1, ramp)
    tail = np.clip((DUR - 0.4 - np.arange(N) / SR) / 2.2, 0, 1) ** 0.8
    music *= (gate * tail)[:, None]
    hits = buf()
    add(hits, rc, 0, 0.12)
    for t in (drop, g1):                                      # a low hit on the drop and under the name
        add(hits, sfx_thud(0.9)[: at(3)], t, 0.22)
    return music, buf(), buf(), hits


def build_sfx():
    out = buf()
    trims = getattr(F, "SFX_TRIM", {})             # per film, in dB, by cue type
    for c in CUES:
        t, v = c["t"], c.get("v", 1.0)
        k = c["type"]
        if k.startswith("m_"):                  # marks for the music, not sounds
            continue
        tg = 10 ** (trims.get(k, 0.0) / 20)
        add = lambda dst, x, t_, gain=1.0, pan=0.0: add_(dst, x, t_, gain * tg, pan)
        if k == "key":
            add(out, sfx_key(v), t, 0.22, pan=rng.uniform(-.15, .15))
        elif k == "space":
            add(out, sfx_key(0.8), t, 0.18)
        elif k == "stamp":
            add(out, sfx_paper(v) * 0.6 + np.pad(sfx_key(1), (0, at(0.22) - at(0.06)))[: at(0.22)] * 0.3, t, 0.22)
        elif k == "whoosh":
            d = c.get("d", .5); add(out, sfx_whoosh(d, v), t - d * 0.55, 0.22)
        elif k == "paper":
            add(out, sfx_paper(v), t, 0.3, pan=c.get("pan", 0) * 0.6)
        elif k == "tick":
            add(out, sfx_tick(v), t, 0.2, pan=rng.uniform(-.3, .3))
        elif k == "blip":
            add(out, sfx_blip(v), t, 0.16, pan=rng.uniform(-.3, .3))
        elif k == "pop":
            add(out, sfx_pop(v), t, 0.22)
        elif k == "click":
            add(out, sfx_click(), t, 0.4, pan=0.2)
        elif k == "scan":
            add(out, sfx_scan(c["d"]), t, 0.2, pan=-0.2)
        elif k == "swish":
            add(out, sfx_swish(v), t - 0.1, 0.12)
        elif k == "type":
            add(out, sfx_type(c.get("d", .2), v), t, 0.16, pan=0.25)
        elif k == "alert":
            add(out, sfx_alert(v), t, 0.35)
        elif k == "riser":
            d = c["d"]; add(out, sfx_riser(d), t - d, 0.17)
        elif k == "implode":
            d = c["d"]; add(out, sfx_implode(d), t - d, 0.3)
        elif k == "impact":
            add(out, reverb(sfx_impact(v), IR_HALL, 0.35), t, 0.4)
        elif k == "shimmer":
            add(out, reverb(sfx_shimmer(c.get("d", 2), v), IR_HALL, 0.6), t, 0.55)
        elif k == "zip":
            add(out, sfx_zip(c.get("d", .4)), t, 0.1)
        elif k == "toggle":
            add(out, sfx_toggle(), t, 0.3)
        elif k == "hit":
            add(out, reverb(sfx_hit(v), IR_ROOM, 0.3), t, 0.3)
        elif k == "draw":
            add(out, sfx_draw(c["d"]), t, 0.5)
        elif k == "fall":
            add(out, sfx_fall(c["d"]), t, 0.5)
        elif k == "boot":
            add(out, reverb(sfx_boot(), IR_HALL, 0.3), t, 0.5)
        elif k == "send":
            add(out, sfx_send(), t - 0.05, 0.3, pan=0.3)
        elif k == "recv":
            add(out, sfx_recv(), t, 0.28 * v if v != 1.0 else 0.28, pan=-0.25)
        elif k == "whip":
            add(out, sfx_whip(), t - 0.15, 0.3)
        elif k == "wipe":
            add(out, sfx_whoosh(0.3, 1.0, up=True), t - 0.28, 0.28)
            add(out, reverb(kick(0.8), IR_ROOM, 0.3), t, 0.3)
        elif k == "flip":
            add(out, sfx_flip(), t, 0.25 * v / .35, pan=rng.uniform(-.4, .4))
        elif k == "star":
            add(out, reverb(sfx_star(v), IR_HALL, 0.3), t, 0.35)
        elif k == "drop":
            add(out, sfx_drop(c["deg"], c.get("n", 1), c.get("step", 2), c.get("gap", 0.05), c.get("wet", 0.6), v, seed=int(t * 1000)), t, 0.5)
        elif k == "msgin":
            add(out, sfx_msgin(v), t, 0.35, pan=-0.2)
        elif k == "msgout":
            add(out, sfx_msgout(v), t - 0.05, 0.35, pan=0.2)
        elif k == "confirm":
            add(out, sfx_confirm(c.get("n", 2), c.get("deg", 3), v), t, 0.3)
        elif k == "connect":
            add(out, sfx_connect(v), t, 0.35)
        elif k == "tension":
            add(out, sfx_tension(c["d"], v), t, 0.45)
        elif k == "hum":
            add(out, sfx_hum(c["d"], v), t, 0.3)
        elif k == "glitch":
            add(out, sfx_glitch(c["d"]), t, 0.3)
        elif k == "thud":
            # the hit is the moment, but the tagline follows it within a second
            th = sfx_thud(v); th *= np.exp(-np.arange(len(th)) / SR / 0.5)
            add(out, reverb(th, IR_ROOM, 0.3), t, 0.45)
        else:
            raise ValueError(k)
    dr = getattr(F, "SFX_DROWN", None)
    if dr:
        out = drown(out, **dr)
    return out


# ------------------------------------------------------------------ voice
def build_vo():
    vo = np.zeros(N)
    if not TL["clips"]:                         # a film with no voice
        return np.zeros((N, 2)), np.zeros(N)
    for c in TL["clips"]:
        a, sr = sf.read(os.path.join(BUILD, c["file"]), dtype="float64")
        a = signal.resample_poly(a, SR, sr)
        i = at(c["start"]); vo[i:i + len(a)] += a[: N - i]
    vo = hp(vo, 75, 4)
    vo = peak_eq(vo, 180, -1.5, 0.8)       # a little less box
    vo = peak_eq(vo, 3200, 2.5, 0.9)       # presence
    vo = peak_eq(vo, 11000, 1.5, 0.7)      # air
    # gentle RMS compressor, 3:1 above -20 dBFS
    env = np.sqrt(signal.lfilter([0.002], [1, -0.998], vo ** 2) + 1e-12)
    lvl = 20 * np.log10(env / np.abs(vo).max() + 1e-9)
    gr = np.where(lvl > -20, (lvl + 20) * (1 - 1 / 3), 0)
    vo = vo * 10 ** (-gr / 20)
    vo = vo / np.abs(vo).max() * 0.8
    st = reverb(vo, IR_ROOM, 0.06)
    # how present the voice is, for ducking the music under it
    e = np.abs(vo)
    att, rel = np.exp(-1 / (0.03 * SR)), np.exp(-1 / (0.35 * SR))
    # a fast follower is too slow in pure python; approximate with two one-pole filters
    fast = signal.lfilter([1 - att], [1, -att], e)
    slow = signal.lfilter([1 - rel], [1, -rel], np.maximum(fast, 0))
    presence = np.clip(np.maximum(fast, slow) / 0.08, 0, 1)
    presence = signal.lfilter([1 - rel], [1, -rel], presence)
    return st, np.clip(presence * 1.6, 0, 1)


# ------------------------------------------------------------------ master
def limiter(x, ceiling_db=-1.2, look=0.004, release=0.08):
    """Look-ahead peak limiter on a 4x oversampled peak estimate."""
    ceil = 10 ** (ceiling_db / 20)
    up = np.abs(signal.resample_poly(x, 4, 1, axis=0)).max(1)
    pk = np.pad(up, (0, 4 * len(x) - len(up)))[: 4 * len(x)].reshape(-1, 4).max(1)
    need = np.minimum(1, ceil / np.maximum(pk, 1e-9))
    la = int(look * SR)
    need = np.minimum.reduce([np.roll(need, -k) for k in range(0, la, max(1, la // 8))])
    rel = np.exp(-1 / (release * SR))
    g = signal.lfilter([1 - rel], [1, -rel], need - 1) + 1
    g = np.minimum(g, need)
    return x * g[:, None]

def main():
    os.makedirs(os.path.join(BUILD, "stems"), exist_ok=True)
    style = getattr(F, "MUSIC", "synth")
    drum_led = style in ("drums", "band", "garage", "perc", "electronica", "reel", "file")
    pads, bass, keys, drums = {"drums": build_music_drums, "band": build_music_band, "garage": build_music_garage, "perc": build_music_perc,
                               "electronica": build_music_electronica, "reel": reel_style(), "file": build_music_file}.get(style, build_music)()
    music = pads * 1.0 + bass * 1.0 + keys * 1.0 + drums * (1.0 if drum_led else 0.9)
    if style != "file":                                     # a generated track comes mixed
        music = peak_eq(music, 2800, 3.0, 0.6)
        music = peak_eq(music, 90, -2.0, 0.8)
    sfx = build_sfx()
    vo, presence = build_vo()
    speaking = np.zeros(N)
    for l in TL["lines"]:
        speaking[at(l["start"] - 0.12):at(l["end"] + 0.25)] = 1
    # percussion only: a small, slow dip, so the level never jumps between lines
    rel = np.exp(-1 / ((0.45 if style in ("perc", "electronica") else 0.12) * SR))
    speaking = signal.lfilter([1 - rel], [1, -rel], speaking)
    # drums and a band sit further down under the voice: claps and chords share its range
    duck_db = {"perc": -3.5, "electronica": -3.5, "band": -9.0, "garage": -8.0, "drums": -7.5}.get(style, -6.0) * np.clip(speaking, 0, 1)
    music *= 10 ** (duck_db / 20)[:, None]
    # the last seconds breathe out
    fade = np.clip((DUR - np.arange(N) / SR) / 1.4, 0, 1) ** 1.5
    fade_in = np.clip(np.arange(N) / SR / 0.05, 0, 1)
    mg, sg = getattr(F, "MUSIC_GAIN", 0.46), getattr(F, "SFX_GAIN", 0.45)
    mix = (music * mg + sfx * sg + vo * 1.0) * (fade * fade_in)[:, None]
    mix = mix[: int(DUR * SR)]
    for name, st in [("music", music * mg), ("sfx", sfx * sg), ("vo", vo)]:
        sf.write(os.path.join(BUILD, "stems", name + ".wav"), st[: int(DUR * SR)], SR, subtype="PCM_24")
    meter = pyln.Meter(SR)
    # a little over -14: package.py trims the AAC by about this much to hold its true peak
    target = -13.4
    for _ in range(3):
        loud = meter.integrated_loudness(mix)
        mix = mix * 10 ** ((target - loud) / 20)
        mix = limiter(mix, -2.0)
    loud = meter.integrated_loudness(mix)
    tp = 20 * np.log10(np.abs(signal.resample_poly(mix, 4, 1, axis=0)).max())
    sf.write(os.path.join(BUILD, "mix.wav"), mix, SR, subtype="PCM_24")
    print(f"mix: {len(mix) / SR:.2f}s  {loud:.1f} LUFS  true peak {tp:.2f} dBTP")


if __name__ == "__main__":
    main()
