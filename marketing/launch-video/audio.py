    guitar *= chord_duck; muted *= chord_duck; piano *= chord_duck; brs *= chord_duck
    brs = reverb(brs, IR_HALL, 0.22)
    drums = hp(reverb(drums, IR_ROOM, 0.12), 30)
    bass = hp(bass, 34)
    keys = guitar + muted + whistle + glk
    pads = piano + brs
    return pads, bass, keys, drums

